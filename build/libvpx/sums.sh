#!/bin/sh
# Writes build/libvpx/SHA256SUMS and vpx/internal/native/sums.go from the committed artifacts.
# Usage: sums.sh [outroot]   (reads the artifacts of this tree; writes nothing and says so when one is missing)
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(dirname "$(dirname "$here")")
out=${1:-$root}
n=$root/vpx/internal/native
targets="darwin/amd64 darwin/arm64 linux/amd64 linux/arm64 windows/amd64 windows/arm64"

hostsha() { if command -v sha256sum >/dev/null; then sha256sum "$1"; else shasum -a 256 "$1"; fi | cut -d' ' -f1; }
ext() { case $1 in darwin) echo dylib ;; windows) echo dll ;; *) echo so ;; esac; }

for t in $targets; do
	f=$n/libkolovpx-$(echo "$t" | tr / -).$(ext "${t%/*}")
	[ -f "$f" ] || { echo "sums.sh: $f is missing, nothing written" >&2; exit 0; }
done
[ -f "$here/kolovpx.wasm" ] || { echo "sums.sh: kolovpx.wasm is missing, nothing written" >&2; exit 0; }

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
{
	echo "$(hostsha "$here/kolovpx.wasm")  kolovpx.wasm"
	for t in $targets; do
		b=libkolovpx-$(echo "$t" | tr / -).$(ext "${t%/*}")
		echo "$(hostsha "$n/$b")  ../../vpx/internal/native/$b"
	done
} >"$tmp/SHA256SUMS"
{
	echo '// Code generated by build/libvpx/sums.sh; DO NOT EDIT.'
	echo
	echo 'package native'
	echo
	echo '// libSum is the SHA-256 (hex) and size of an embedded library.'
	echo 'type libSum struct {'
	echo '	SHA256 string'
	echo '	Size   int'
	echo '}'
	echo
	echo '// sums holds the checksum of the library built for each GOOS/GOARCH.'
	echo 'var sums = map[string]libSum{'
	for t in $targets; do
		f=$n/libkolovpx-$(echo "$t" | tr / -).$(ext "${t%/*}")
		echo "	\"$t\": {\"$(hostsha "$f")\", $(wc -c <"$f" | tr -d ' ')},"
	done
	echo '}'
} >"$tmp/sums.go"
gofmt -w "$tmp/sums.go"

put() { if cmp -s "$1" "$2"; then echo "$2: unchanged"; else cp "$1" "$2.new" && mv "$2.new" "$2"; echo "$2: written"; fi; }
mkdir -p "$out/build/libvpx" "$out/vpx/internal/native"
put "$tmp/SHA256SUMS" "$out/build/libvpx/SHA256SUMS"
put "$tmp/sums.go" "$out/vpx/internal/native/sums.go"
