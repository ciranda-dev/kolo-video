package kolovideo

import (
	"bytes"
	"fmt"
	"image"
	"image/jpeg"
)

// decodeMJPEG decodes one Motion-JPEG frame of the given size to I420.
// Many cameras omit the Huffman tables and rely on the default ones from
// ITU-T T.81 Annex K.3, so they are inserted when missing. data may be device
// memory: it is copied once and every later parse reads the copy.
func decodeMJPEG(data []byte, width, height int) (*Frame, error) {
	data, err := withHuffmanTables(data)
	if err != nil {
		return nil, err
	}
	cfg, err := jpeg.DecodeConfig(bytes.NewReader(data))
	if err != nil {
		return nil, fmt.Errorf("%w: %v", ErrInvalidFrame, err)
	}
	if cfg.Width != width || cfg.Height != height {
		return nil, fmt.Errorf("%w: JPEG is %dx%d, want %dx%d", ErrInvalidFrame, cfg.Width, cfg.Height, width, height)
	}
	img, err := jpeg.Decode(bytes.NewReader(data))
	if err != nil {
		return nil, fmt.Errorf("%w: %v", ErrInvalidFrame, err)
	}
	if img.Bounds() != image.Rect(0, 0, width, height) {
		return nil, fmt.Errorf("%w: JPEG decoded to %v", ErrInvalidFrame, img.Bounds())
	}
	f, err := NewFrame(width, height)
	if err != nil {
		return nil, err
	}
	switch m := img.(type) {
	case *image.YCbCr:
		copyYCbCr(f, m)
	case *image.Gray:
		for y := range height {
			copy(f.Y[y*f.YStride:y*f.YStride+width], m.Pix[y*m.Stride:])
		}
	default:
		return nil, fmt.Errorf("%w: JPEG color model %T", ErrUnsupportedFormat, img)
	}
	// JPEG (JFIF) samples are full range.
	f.fullToLimited()
	return f, nil
}

// copyYCbCr copies any chroma subsampling to 4:2:0 by averaging the chroma
// samples under each 2x2 luma block.
func copyYCbCr(f *Frame, m *image.YCbCr) {
	b := m.Rect
	for y := range f.Height {
		off := m.YOffset(b.Min.X, b.Min.Y+y)
		copy(f.Y[y*f.YStride:y*f.YStride+f.Width], m.Y[off:])
	}
	cw, ch := (f.Width+1)/2, (f.Height+1)/2
	for cy := range ch {
		for cx := range cw {
			var us, vs, n int
			for y := 2 * cy; y < 2*cy+2 && y < f.Height; y++ {
				for x := 2 * cx; x < 2*cx+2 && x < f.Width; x++ {
					o := m.COffset(b.Min.X+x, b.Min.Y+y)
					us += int(m.Cb[o])
					vs += int(m.Cr[o])
					n++
				}
			}
			f.U[cy*f.UVStride+cx] = byte((us + n/2) / n)
			f.V[cy*f.UVStride+cx] = byte((vs + n/2) / n)
		}
	}
}

// withHuffmanTables returns a private copy of data with the default DHT segment
// inserted before the first SOS marker when no DHT segment precedes it.
func withHuffmanTables(data []byte) ([]byte, error) {
	if len(data) < 4 || data[0] != 0xff || data[1] != 0xd8 {
		return nil, fmt.Errorf("%w: not a JPEG image", ErrInvalidFrame)
	}
	i := 2
	for i+4 <= len(data) {
		if data[i] != 0xff {
			return nil, fmt.Errorf("%w: bad JPEG marker at %d", ErrInvalidFrame, i)
		}
		marker := data[i+1]
		switch {
		case marker == 0xff:
			i++ // fill byte
			continue
		case marker == 0xc4:
			return bytes.Clone(data), nil
		case marker == 0xda:
			out := make([]byte, 0, len(data)+len(defaultDHT))
			out = append(out, data[:i]...)
			out = append(out, defaultDHT...)
			return append(out, data[i:]...), nil
		case marker == 0x01 || (marker >= 0xd0 && marker <= 0xd7):
			i += 2
			continue
		}
		n := int(data[i+2])<<8 | int(data[i+3])
		if n < 2 {
			return nil, fmt.Errorf("%w: bad JPEG segment length at %d", ErrInvalidFrame, i)
		}
		i += 2 + n
	}
	return nil, fmt.Errorf("%w: JPEG has no scan", ErrInvalidFrame)
}

